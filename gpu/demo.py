MODELS = [("база", "Qwen/Qwen3.5-4B", None, 1.98, "ours"),
          ("tev1", "togethercomputer/Tev1-4B-experimental", None, 2.28, "tev1"),
          ("v3", "Qwen/Qwen3.5-4B", "out/v3/best", 1.18, "ours")]


def rows():
    out = []
    for name, gold_name, state, q, opts, gold in CASES:
        out.append({"name": name, "gold_name": gold_name, "task": "demo", "state": state, "question": q,
                    "options": [{"label": LETTERS[i], "key": f"o{i}", "description": d} for i, d in enumerate(opts)],
                    "answer": LETTERS[gold]})
    return out


def main():
    data = rows()
    res = {r["name"]: {} for r in data}
    for mname, path, adapter, T, style in MODELS:
        tok = AutoTokenizer.from_pretrained(path)
        pad = tok.pad_token_id if tok.pad_token_id is not None else tok.eos_token_id
        lids = letter_ids(tok)
        model = AutoModelForCausalLM.from_pretrained(path, dtype=torch.bfloat16, device_map={"": 0})
        if adapter:
            model = PeftModel.from_pretrained(model, adapter)
        model.eval()
        for r in data:
            r["_ids"] = render(tok, r, style)
            with torch.no_grad():
                sub, _ = option_logits(model, *collate([r], pad, "cuda")[:4], lids)
            p = (sub[0, :len(r["options"])] / T).softmax(-1).tolist()
            res[r["name"]][mname] = [round(x, 3) for x in p]
        del model
        torch.cuda.empty_cache()
    for r in data:
        g = LETTERS.index(r["answer"])
        line = f"{r['name']:30s} верно={r['answer']} "
        for m in ["база", "tev1", "v3"]:
            p = res[r["name"]][m]
            k = max(range(len(p)), key=p.__getitem__)
            line += f"| {m}: {LETTERS[k]} {p[k]:.2f}{' ✓' if k == g else ' ✗'} "
        print(line)
    json.dump({"cases": [{k: v for k, v in r.items() if k != "_ids"} for r in data], "probs": res},
              open("results/demo.json", "w"), ensure_ascii=False, indent=1)


if __name__ == "__main__":
    main()
