"""Генератор синтетических бизнес-политик для v2.

Каждое семейство — регламент с упорядоченными правилами (применяется первое сработавшее),
случайными порогами и полями заявки. Правильный ответ вычисляется кодом, поэтому разметка точная.
Вариант «проверки кодом»: в state добавляются уже вычисленные условия — модель лишь выбирает действие.
"""
import random

NONE_KEY = "none"
NONE_DESC = "Недостаточно данных для решения — передать человеку."
FREE_TEXT = True  # v4.1: часть фактов — живым текстом (для v4 был False)
CALC_KEY = "calc"
CALC_DESC = "Нужен точный расчёт — передать на проверку."
# правила, требующие арифметики между полями (проценты, суммы, разности): без готовой проверки модель не решает сама
CALC = {"discount": {"reject_margin"}, "hiring": {"hr_director"}, "loan": {"reject_pdn"},
        "overtime": {"year_limit"}, "t_credit": {"committee"}}



def rub(x):
    return f"{x:,.0f}".replace(",", " ") + " ₽"


def yn(b):
    return "да" if b else "нет"


class Family:
    def __init__(self, name, title, entity, question, fields, params, rules, default):
        self.name, self.title, self.entity, self.question = name, title, entity, question
        self.fields = fields      # [(label, gen(rng) -> value, fmt(value) -> str)]
        self.params = params      # gen(rng) -> dict порогов
        self.rules = rules        # [(key, desc, text(p) -> str, pred(v, p) -> bool, [labels])]
        self.default = default    # (key, desc)


def F(label, gen, fmt=str):
    return (label, gen, fmt)


def decide(fam, p, vals, missing, checks=True):
    """Первое сработавшее правило. Без готовых проверок правило с арифметикой даёт «нужен расчёт»."""
    if missing is not None:
        return NONE_KEY
    calc = CALC.get(fam.name, set())
    for key, _, _, pred, _ in fam.rules:
        if key in calc and not checks:
            return CALC_KEY
        if pred(vals, p):
            return key
    return fam.default[0]


def sample(fam, rng, p_missing=0.03):
    p = fam.params(rng)
    vals = {lab: gen(rng) for lab, gen, _ in fam.fields}
    missing = None
    if rng.random() < p_missing:
        used = sorted({l for r in fam.rules for l in r[4]})
        missing = rng.choice(used)
    return p, vals, missing


def short_name(rule):
    """Короткое имя правила по полям, которые оно проверяет (для фраз о порядке проверки)."""
    labs = rule[4]
    return " и ".join(l.lower() for l in labs[:2])


def render_policy(fam, rng, p, style=None):
    """Пять стилей записи регламента; во всех правильный ответ — первое сработавшее правило по приоритету."""
    texts = [r[2](p) for r in fam.rules]
    default = fam.default[1].rstrip(".").lower()
    style = style if style is not None else rng.randrange(5)
    if style == 0:  # нумерованный список в одну строку
        return (f"{fam.title}. Правила проверяются по порядку, применяется первое подходящее: "
                + "; ".join(f"{i}) {t}" for i, t in enumerate(texts, 1)) + f"; иначе — {default}.")
    if style == 1:  # многострочный список
        return (f"{fam.title}.\n" + "\n".join(f"{i}) {t}" for i, t in enumerate(texts, 1))
                + f"\nЕсли ни одно правило не сработало — {default}. Правила применяются в указанном порядке.")
    if style == 2:  # правила вперемешку + отдельная фраза о порядке проверки
        order = list(range(len(texts)))
        shuffled = order[:]
        rng.shuffle(shuffled)
        body = "; ".join(texts[i] for i in shuffled)
        seq = ", затем ".join(short_name(fam.rules[i]) for i in order)
        return (f"{fam.title}: {body}; если ничего не подошло — {default}. "
                f"Порядок проверки (важен, применяется первое сработавшее): {seq}.")
    if style == 3:  # явные приоритеты, перечисление вперемешку
        idx = list(range(len(texts)))
        rng.shuffle(idx)
        body = "\n".join(f"- [приоритет {i + 1}] {texts[i]}" for i in idx)
        return (f"{fam.title}. Если подходят несколько правил, применяется правило с наименьшим номером приоритета.\n"
                f"{body}\n- [по умолчанию] {default}")
    # style 4: связный текст по убыванию приоритета
    sents = [f"Если {t.split(' — ')[0]}, то {t.split(' — ')[-1]}." for t in texts]
    return (f"{fam.title}. Правила перечислены по убыванию приоритета: " + " ".join(sents)
            + f" Во всех остальных случаях — {default}.")


def render_row(fam, rng, split, p, vals, missing, use_checks, make):
    fmt = {lab: f for lab, _, f in fam.fields}
    gold = decide(fam, p, vals, missing, checks=use_checks)
    policy = render_policy(fam, rng, p)
    policy += " Если в документе нет данных, нужных для проверки, — передать человеку."
    items = [(l, fmt[l](v)) for l, v in vals.items() if l != missing]
    rng.shuffle(items)
    fact_style = rng.random() if FREE_TEXT else 1.0
    if fact_style < 0.45:  # живой текст, как в письме (v4.1)
        from narrative import narrate
        facts = narrate(fam.name, fam.entity, vals, fmt, missing, rng)
    elif fact_style < 0.60:  # маркированный список
        facts = f"{fam.entity}:\n" + "\n".join(f"- {l.lower()}: {v}" for l, v in items)
    else:  # поля, как в v1–v4
        facts = f"{fam.entity}: " + "; ".join(f"{l}: {v}" for l, v in items)
    state = policy + "\n" + facts
    if use_checks and missing is None:
        res = [f"правило {i}: {'выполнено' if r[3](vals, p) else 'не выполнено'}"
               for i, r in enumerate(fam.rules, 1)]
        state += "\nАвтоматические проверки (вычислены системой): " + "; ".join(res)
    seen, uniq = set(), []
    extra = [(CALC_KEY, CALC_DESC)] if fam.name in CALC else []
    for k, d in [(k, d) for k, d, *_ in fam.rules] + [fam.default, (NONE_KEY, NONE_DESC)] + extra:
        if k not in seen:
            seen.add(k)
            uniq.append((k, d))
    row = make(fam.name, split, state, fam.question, uniq, gold, rng)
    row["checks"] = bool(use_checks and missing is None)
    return row


def build(fam, rng, split, p_missing=0.03, p_checks=0.3, checks=None, make=None):
    p, vals, missing = sample(fam, rng, p_missing)
    use_checks = checks if checks is not None else (rng.random() < p_checks)
    return render_row(fam, rng, split, p, vals, missing, use_checks, make)


def build_pair(fam, rng, split, p_checks=0.3, make=None, tries=40):
    """Контрастная пара: меняем одно поле так, чтобы правильный ответ изменился (рецепт Nimble)."""
    p, vals, _ = sample(fam, rng, p_missing=0.0)
    use_checks = rng.random() < p_checks
    gold = decide(fam, p, vals, None, checks=use_checks)
    gens = {lab: gen for lab, gen, _ in fam.fields}
    for _ in range(tries):
        lab = rng.choice(list(gens))
        v2 = dict(vals)
        v2[lab] = gens[lab](rng)
        if decide(fam, p, v2, None, checks=use_checks) != gold:
            a = render_row(fam, rng, split, p, vals, None, use_checks, make)
            b = render_row(fam, rng, split, p, v2, None, use_checks, make)
            a["pair"] = b["pair"] = f"{fam.name}-{id(a)}"
            return [a, b]
    return []


def R(lo, hi, step=1):
    return lambda rng: rng.randrange(lo, hi + 1, step)


def B(p=0.5):
    return lambda rng: rng.random() < p


def C(*xs):
    return lambda rng: rng.choice(xs)


