OPENERS = {"default": ["Добрый день! ", "Здравствуйте. ", "Коллеги, ", "", "Ситуация такая: ", "Пишу по заявке: "]}


def narrate(fam_name, entity, vals, fmt, missing, rng):
    """Описание случая живым текстом; поля без шаблона — нейтрально «поле — значение»."""
    tmpl = P.get(fam_name, {})
    parts = []
    for lab, v in vals.items():
        if lab == missing:
            continue
        parts.append(tmpl[lab](v) if lab in tmpl else f"{lab.lower()} — {fmt[lab](v)}")
    rng.shuffle(parts)
    text = ", ".join(parts)
    text = text[0].upper() + text[1:] + "."
    style = rng.random()
    if style < 0.4:
        return f"{entity}. {rng.choice(OPENERS['default'])}{text}"
    if style < 0.7:
        return f"Письмо по теме «{entity.lower()}»: {rng.choice(OPENERS['default'])}{text} Прошу принять решение."
    return f"{entity}: {text}"
